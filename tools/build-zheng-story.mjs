import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const storyPath = path.join(projectRoot, 'docs/narrative/zheng-zhilong-story.json');
export const readerDirectory = path.join(projectRoot, 'docs/narrative/zheng-zhilong');
export const outputPath = path.join(readerDirectory, 'story-data.js');
export const jsonMirrorPath = path.join(readerDirectory, 'zheng-zhilong-story.json');

// Escape HTML script terminators and JavaScript line separators without changing
// any text seen by the reader. No clock or working-directory input: reproducible.
export function serializeStory(story) {
  if (!story || typeof story !== 'object' || Array.isArray(story)) {
    throw new TypeError('Story root must be a JSON object.');
  }
  const escaped = JSON.stringify(story, null, 2).replace(/[<\u2028\u2029]/g, character => ({
    '<': '\\u003c',
    '\u2028': '\\u2028',
    '\u2029': '\\u2029',
  })[character]);
  return `// Generated by tools/build-zheng-story.mjs. Edit zheng-zhilong-story.json.\nwindow.ZHENG_STORY = ${escaped};\n`;
}

export async function buildStory() {
  const sourceBytes = await readFile(storyPath);
  const story = JSON.parse(sourceBytes.toString('utf8').replace(/^\uFEFF/, ''));
  const output = serializeStory(story);
  await mkdir(readerDirectory, { recursive: true });
  await writeFile(outputPath, output, 'utf8');
  await writeFile(jsonMirrorPath, sourceBytes);
  return { outputPath, jsonMirrorPath, bytes: Buffer.byteLength(output),
    mirrorBytes: sourceBytes.length, acts: story.acts?.length ?? 0 };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv.length > 2) throw new Error('Usage: node tools/build-zheng-story.mjs');
    const result = await buildStory();
    console.log(`Built ${path.relative(projectRoot, result.outputPath)} (${result.bytes} bytes; ${result.acts} acts).`);
    console.log(`Mirrored ${path.relative(projectRoot, result.jsonMirrorPath)} (${result.mirrorBytes} bytes).`);
  } catch (error) {
    console.error(`Story build failed: ${error.message}`);
    process.exitCode = 1;
  }
}
