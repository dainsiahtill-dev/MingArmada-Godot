import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {inspectImage} from '../../../tools/verify-zheng-story.mjs';
const dir=path.dirname(fileURLToPath(import.meta.url));
const [id,sourcePath]=process.argv.slice(2);
if(!/^zzl_a[1-6]_s[1-4]_0[12]$/.test(id||''))throw new Error('Invalid illustration identity');
const source=path.resolve(sourcePath||'');
const allowed=path.resolve('C:/Users/dains/.codex/generated_images')+path.sep;
if(!source.startsWith(allowed)||!source.endsWith('.png'))throw new Error('Expected built-in generated PNG');
const bytes=fs.readFileSync(source),sha256=crypto.createHash('sha256').update(bytes).digest('hex');
if(!bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))throw new Error('Not PNG');
const info=inspectImage(bytes);
if(info.format!=='PNG')throw new Error('Expected complete PNG raster');
const target=path.resolve(dir,'../zheng-zhilong/images/illustrated-2026-10-24',id+'.png');
if(fs.existsSync(target)&&!fs.readFileSync(target).equals(bytes))throw new Error('Existing selected image differs; save a separate revision before replacing');
fs.mkdirSync(path.dirname(target),{recursive:true});fs.copyFileSync(source,target);
const receiptDir=path.join(dir,'receipts');fs.mkdirSync(receiptDir,{recursive:true});
const report={id,provider:'ChatGPT built-in image_gen',generatedFile:source,selectedFile:path.relative(path.resolve(dir,'../../..'),target).replaceAll('\\','/'),sha256,bytes:bytes.length,width:info.width,height:info.height,recordedAt:new Date().toISOString()};
fs.writeFileSync(path.join(receiptDir,id+'.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
