import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {renderRebootExports,editorialOutputDirectory} from '../../../tools/render-zheng-reboot-exports.mjs';
const dir=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(dir,'../../..'),reader=path.join(root,'docs/narrative/zheng-zhilong');
const source=fs.readFileSync(path.resolve(dir,'../zheng-zhilong-story.json')),story=JSON.parse(source);
if(story.version!=='historical-reboot-polish-2026-10-24'||path.resolve(root,editorialOutputDirectory(story))!==dir)throw new Error('Expected adopted full-polish edition');
for(const [file,content] of Object.entries(renderRebootExports(story)))fs.writeFileSync(path.join(file==='CAUSE-CHAIN.md'?dir:reader,file),content);
const htmlFile=path.join(reader,'index.html');let html=fs.readFileSync(htmlFile,'utf8');
html=html.replace(/((?:src|href)="(?:styles\.css|story-data\.js|app\.js))(?:\?[^" ]*)?"/g,'$1?v=20261024-full-polish"');
fs.writeFileSync(htmlFile,html);
const appFile=path.join(reader,'app.js');let app=fs.readFileSync(appFile,'utf8');
app=app.replace('史料重构新作 · 2026年10月24日更新','史料重构 · 全卷精修 · 2026年10月24日更新');
fs.writeFileSync(appFile,app);
fs.writeFileSync(path.join(reader,'illustration-manifest.json'),JSON.stringify({schemaVersion:1,storyVersion:story.version,updated:'2026-10-24',illustrations:[],scope:'Text-only historical novel; no previous scene art adopted.'},null,2)+'\n');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const record={sourceSha256:hash(source),version:story.version,files:['novel.md','screenplay.md','game-scenes.md'].map(file=>{const b=fs.readFileSync(path.join(reader,file));return {file,bytes:b.length,sha256:hash(b)};})};
fs.writeFileSync(path.join(dir,'export-verification.json'),JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify(record));
